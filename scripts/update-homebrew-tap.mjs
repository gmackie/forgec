#!/usr/bin/env node
/**
 * Render a Homebrew formula from release artifacts and push it to a shared tap.
 *
 * Deliberately generic: every CLI we publish uses the same tap
 * (`gmackorg/homebrew-tap`) and the same artifact convention, so this script is
 * copied unchanged into each repository and driven entirely by environment.
 *
 *   FORMULA    formula + binary name          (e.g. forgec)
 *   VERSION    release version, no leading v  (e.g. 0.3.0)
 *   REPO       owner/repo of the release      (e.g. gmackorg/forgegraph)
 *   TAP_REPO   owner/repo of the tap          (default gmackorg/homebrew-tap)
 *   DIST_DIR   directory holding <name>-<version>-<target>.tar.gz(.sha256)
 *   TAP_TOKEN  a token with push rights on the tap
 *   DRY_RUN    "true" renders and prints without pushing
 *
 * Artifacts are expected as `<FORMULA>-<VERSION>-<rust target triple>.tar.gz`
 * with a sibling `.sha256`. Missing platforms are simply omitted from the
 * formula rather than guessed.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const env = (k, fallback) => {
  const v = process.env[k] ?? fallback;
  if (v === undefined) throw new Error(`${k} is required`);
  return v;
};

const FORMULA = env("FORMULA");
const VERSION = env("VERSION").replace(/^v/, "");
const REPO = env("REPO");
const TAP_REPO = env("TAP_REPO", "gmackorg/homebrew-tap");
const DIST = resolve(env("DIST_DIR", "dist"));
const DRY = env("DRY_RUN", "false") === "true";

const TARGETS = {
  "aarch64-apple-darwin": { os: "macos", cpu: "arm" },
  "x86_64-apple-darwin": { os: "macos", cpu: "intel" },
  "aarch64-unknown-linux-gnu": { os: "linux", cpu: "arm" },
  "x86_64-unknown-linux-gnu": { os: "linux", cpu: "intel" },
};

const assets = [];
for (const file of readdirSync(DIST)) {
  const m = new RegExp(`^${FORMULA}-${VERSION.replace(/\./g, "\\.")}-(.+)\\.tar\\.gz$`).exec(file);
  if (!m) continue;
  const target = m[1];
  const spec = TARGETS[target];
  if (!spec) continue;
  const shaFile = join(DIST, `${file}.sha256`);
  if (!existsSync(shaFile)) throw new Error(`${file} has no .sha256 beside it; refusing to publish a formula without a checksum`);
  assets.push({ ...spec, target, file, sha256: readFileSync(shaFile, "utf8").trim().split(/\s+/)[0] });
}
if (assets.length === 0) throw new Error(`no ${FORMULA}-${VERSION}-<target>.tar.gz artifacts found in ${DIST}`);

const url = (a) => `https://github.com/${REPO}/releases/download/v${VERSION}/${a.file}`;
const className = FORMULA.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const block = (os, cpu) => {
  const a = assets.find((x) => x.os === os && x.cpu === cpu);
  return a ? `        url "${url(a)}"\n        sha256 "${a.sha256}"` : null;
};

const platform = (os) => {
  const arm = block(os, "arm");
  const intel = block(os, "intel");
  if (!arm && !intel) return "";
  const parts = [];
  if (arm) parts.push(`      if Hardware::CPU.arm?\n${arm}`);
  if (intel) parts.push(`      ${arm ? "els" : ""}if Hardware::CPU.intel?\n${intel}`);
  return `    on_${os} do\n${parts.join("\n")}\n      end\n    end\n`;
};

const desc = {
  forgec: "ForgeGraph compiler: one package, equivalent behaviour on Cloudflare, AWS and Node",
}[FORMULA] ?? `${FORMULA} command line`;

const formula = `# Generated by scripts/update-homebrew-tap.mjs from the v${VERSION} release. Do not edit by hand.
class ${className} < Formula
  desc "${desc}"
  homepage "https://github.com/${REPO}"
  version "${VERSION}"
  license "Apache-2.0"

${platform("macos")}${platform("linux")}
  def install
    bin.install "${FORMULA}"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${FORMULA} --version")
  end
end
`;

const target = `Formula/${FORMULA}.rb`;
console.error(`--- ${target} ---\n${formula}`);
if (DRY) {
  console.error(`DRY_RUN: not pushing to ${TAP_REPO}`);
  process.exit(0);
}

const token = env("TAP_TOKEN");
const dir = mkdtempSync(join(tmpdir(), "tap-"));
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { cwd: dir, stdio: "inherit", ...opts });
execFileSync("git", ["clone", "--depth", "1", `https://x-access-token:${token}@github.com/${TAP_REPO}.git`, dir], { stdio: "inherit" });
mkdirSync(join(dir, "Formula"), { recursive: true });
writeFileSync(join(dir, target), formula);
run("git", ["config", "user.name", "forgegraph-release"]);
run("git", ["config", "user.email", "release@forgegraf.com"]);
run("git", ["add", target]);
const changed = execFileSync("git", ["status", "--porcelain", target], { cwd: dir, encoding: "utf8" }).trim();
if (!changed) {
  console.error(`${target} is already at v${VERSION}; nothing to push`);
  process.exit(0);
}
run("git", ["commit", "-m", `${FORMULA} ${VERSION}`]);
run("git", ["push"]);
console.error(`pushed ${target} ${VERSION} to ${TAP_REPO}`);
