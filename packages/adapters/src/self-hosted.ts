/**
 * Docker and Nix self-hosted packaging (FORGE-075/076; PAR-152/153). Emits a
 * reproducible multi-stage Dockerfile (pinned base digest placeholder, nonroot
 * user, read-only filesystem, health/shutdown wiring), a Compose topology
 * (api, worker, postgres, optional MinIO) and a Nix flake with a NixOS module.
 * Secrets appear only as references (environment variable names, files under
 * `/run/secrets`, systemd `LoadCredential`); the emitter takes secret
 * *references*, never values, so no secret byte can enter an image layer or
 * the Nix store. Compose supplies Postgres and object storage; it does not
 * claim a workflow engine: the durable in-process driver runs in the worker
 * and the Temporal-backed profile is a separate, separately certified pack.
 */
import type { DeploymentPlan } from "./deployment-plan.js";

export interface SelfHostedPack { files: Record<string, string>; secrets: { name: string; docker: string; nixos: string }[] }

export const BASE_IMAGE = "docker.io/library/node:22-bookworm-slim";

export function emitSelfHosted(plan: DeploymentPlan, o: { baseDigest?: string; temporal?: boolean } = {}): SelfHostedPack {
  if (plan.target !== "self-hosted") throw new Error(`plan target ${plan.target} is not self-hosted`);
  const image = String(plan.resources.find((r) => r.kind === "container")?.properties["image"] ?? `forge-${plan.app}`);
  const base = o.baseDigest ? `${BASE_IMAGE}@${o.baseDigest}` : BASE_IMAGE;
  const secrets = plan.secrets.map((s) => ({ name: s.env, docker: `/run/secrets/${s.env}`, nixos: `\${CREDENTIALS_DIRECTORY}/${s.env}` }));
  const dockerfile = `# syntax=docker/dockerfile:1.7
# Generated by forge (self-hosted pack) for ${plan.app}@${plan.artifact.slice(0, 12)}; reproducible: pin the base by digest.
FROM ${base} AS build
WORKDIR /src
COPY package.json pnpm-lock.yaml ./
RUN corepack enable && pnpm install --frozen-lockfile --prod=false
COPY . .
RUN pnpm -r build && pnpm --filter ./examples/${plan.app.split("-").pop() ?? "app"} exec node deploy/node/bundle.mjs

FROM ${base}
ENV NODE_ENV=production FORGE_ARTIFACT=${plan.artifact}
# secrets are read from files at runtime (compose secrets / systemd credentials); never baked in
ENV ${secrets.map((s) => `${s.name}_FILE=${s.docker}`).join(" ")}
RUN groupadd --system forge && useradd --system --gid forge --home /app forge
WORKDIR /app
COPY --from=build --chown=forge:forge /src/examples/*/deploy/node/dist ./dist
USER forge
EXPOSE 8080
HEALTHCHECK --interval=10s --timeout=3s --retries=3 CMD node -e "fetch('http://127.0.0.1:8080/readyz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"
STOPSIGNAL SIGTERM
ENTRYPOINT ["node", "--enable-source-maps", "dist/server.js"]
`;
  const compose = {
    services: {
      api: { image, read_only: true, tmpfs: ["/tmp"], user: "forge", environment: { FORGE_ROLE: "api", FORGE_PG_URL_FILE: "/run/secrets/FORGE_PG_URL", PORT: "8080" }, secrets: [...plan.secrets.map((s) => s.env), "FORGE_PG_URL"], ports: ["8080:8080"], depends_on: { postgres: { condition: "service_healthy" } }, stop_grace_period: "30s", healthcheck: { test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:8080/readyz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"], interval: "10s", timeout: "3s", retries: 3 } },
      worker: { image, read_only: true, tmpfs: ["/tmp"], user: "forge", environment: { FORGE_ROLE: "worker", FORGE_PG_URL_FILE: "/run/secrets/FORGE_PG_URL" }, secrets: [...plan.secrets.map((s) => s.env), "FORGE_PG_URL"], depends_on: { postgres: { condition: "service_healthy" } }, stop_grace_period: "60s" },
      postgres: { image: "docker.io/library/postgres:17", environment: { POSTGRES_USER: "forge", POSTGRES_DB: "forge", POSTGRES_PASSWORD_FILE: "/run/secrets/POSTGRES_PASSWORD" }, secrets: ["POSTGRES_PASSWORD"], volumes: ["pgdata:/var/lib/postgresql/data"], healthcheck: { test: ["CMD-SHELL", "pg_isready -U forge"], interval: "5s", timeout: "3s", retries: 10 } },
      ...(o.temporal ? { temporal: { image: "docker.io/temporalio/auto-setup:1.25.0", environment: { DB: "postgres12", DB_PORT: "5432", POSTGRES_USER: "forge", POSTGRES_PWD_FILE: "/run/secrets/POSTGRES_PASSWORD", POSTGRES_SEEDS: "postgres" }, secrets: ["POSTGRES_PASSWORD"], depends_on: { postgres: { condition: "service_healthy" } } } } : {}),
    },
    secrets: Object.fromEntries([...plan.secrets.map((s) => s.env), "FORGE_PG_URL", "POSTGRES_PASSWORD"].map((n) => [n, { external: true }])),
    volumes: { pgdata: {} },
    "x-forge": { artifact: plan.artifact, workflows: o.temporal ? "temporal (separately certified profile)" : "in-process durable driver in the worker (node-postgres profile); Compose provides no workflow engine" },
  };
  const flake = `{
  description = "Forge self-hosted pack for ${plan.app} (${plan.artifact.slice(0, 12)})";
  inputs.nixpkgs.url = "github:NixOS/nixpkgs/nixos-24.11";
  outputs = { self, nixpkgs }: let
    systems = [ "x86_64-linux" "aarch64-linux" "aarch64-darwin" ];
    forAll = f: nixpkgs.lib.genAttrs systems (system: f nixpkgs.legacyPackages.\${system});
  in {
    packages = forAll (pkgs: {
      default = pkgs.stdenvNoCC.mkDerivation {
        pname = "forge-${plan.app}";
        version = "${plan.artifact.slice(0, 12)}";
        src = ./dist;
        dontBuild = true;
        installPhase = "mkdir -p $out/lib/forge && cp -r . $out/lib/forge";
        # no secret ever enters this derivation: configuration and credentials are supplied by the NixOS module at runtime
      };
    });
    nixosModules.default = { config, lib, pkgs, ... }: let cfg = config.services.forge-${plan.app}; in {
      options.services.forge-${plan.app} = {
        enable = lib.mkEnableOption "Forge ${plan.app}";
        role = lib.mkOption { type = lib.types.enum [ "api" "worker" ]; default = "api"; };
        port = lib.mkOption { type = lib.types.port; default = 8080; };
        credentials = lib.mkOption { type = lib.types.attrsOf lib.types.path; default = {}; description = "secret name -> file path, loaded with LoadCredential; never placed in the store"; };
      };
      config = lib.mkIf cfg.enable {
        users.users.forge = { isSystemUser = true; group = "forge"; };
        users.groups.forge = {};
        systemd.services."forge-${plan.app}-\${cfg.role}" = {
          wantedBy = [ "multi-user.target" ];
          after = [ "network-online.target" "postgresql.service" ];
          serviceConfig = {
            ExecStart = "\${pkgs.nodejs_22}/bin/node --enable-source-maps \${self.packages.\${pkgs.system}.default}/lib/forge/server.js";
            User = "forge"; Group = "forge";
            DynamicUser = false;
            ProtectSystem = "strict"; ProtectHome = true; PrivateTmp = true; NoNewPrivileges = true;
            LoadCredential = lib.mapAttrsToList (n: p: "\${n}:\${p}") cfg.credentials;
            Environment = [ "FORGE_ROLE=\${cfg.role}" "PORT=\${toString cfg.port}" "FORGE_ARTIFACT=${plan.artifact}" ${secrets.map((s) => `"${s.name}_FILE=%d/${s.name}"`).join(" ")} "FORGE_PG_URL_FILE=%d/FORGE_PG_URL" ];
            KillSignal = "SIGTERM"; TimeoutStopSec = 60;
            Restart = "on-failure";
          };
        };
      };
    };
  };
}
`;
  const readme = `# Self-hosted pack (${plan.app} @ ${plan.artifact.slice(0, 12)})

- Dockerfile: multi-stage, nonroot \`forge\` user, read-only root in Compose, \`/readyz\` health, SIGTERM drain. Pin the base image by digest for reproducibility.
- compose.yaml: api + worker + postgres${o.temporal ? " + temporal" : ""}; secrets are external Compose secrets mounted under /run/secrets (\`*_FILE\` variables); no value is in this pack.
- flake.nix: package (dist only, no secrets in the store) and a NixOS module using systemd \`LoadCredential\`.
- Upgrades and rollbacks run through the deployment ledger (\`forge-migrate\`), the same as every other target: install a new image, run the migration job under its lease, shift traffic, drain.
- Workflows: ${o.temporal ? "Temporal (profile self-hosted-full; certify separately)" : "the in-process durable driver in the worker (profile node-postgres). Compose alone does not provide a workflow engine."}
`;
  return {
    files: { Dockerfile: dockerfile, "compose.yaml": JSON.stringify(compose, null, 2) + "\n", "flake.nix": flake, "README.md": readme, ".dockerignore": "node_modules\n.git\n**/.env*\n**/*.pem\n**/secrets/\n" },
    secrets,
  };
}
