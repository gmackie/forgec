// Builds the WorkerCode for one closure: the closure's js-module units (bytes exactly as sealed),
// the shared libraries they were built against, the app bundle, and a generated main module that
// wires the units into the runtime and turns the host's capability stubs into the binding shapes
// the runtime expects. Module names sit at the root so the units' bare `effect` and
// `@forgegraph/runtime` imports resolve to the linker-provided libraries.
import { jsUnits, LinkError, type ClosureManifest } from "./manifest.ts";
import type { Policy } from "./policy.ts";

/** Library name@version -> blob digest, plus app bundles by buildHash. Produced by scripts/build-libs.mjs. */
export interface LinkerKit {
  libraries: Record<string, string>;
  apps: Record<string, string>;
}

export const RUNTIME_LIBRARY = "@forgegraph/runtime";
export const EFFECT_LIBRARY = "effect";
export const COMPATIBILITY_DATE = "2026-09-25";

export interface ChildModules {
  [name: string]: string | { js: string } | { json: unknown };
}

export interface ChildSource {
  /** Blob digests the child needs, by module name. */
  blobs: Record<string, string>;
  /** Libraries required by the closure, name -> version. */
  libraries: Record<string, string>;
  units: Array<{ hash: string; symbol: string; abi: string; moduleName: string }>;
}

const executorVersion = (manifest: ClosureManifest): string => {
  const executors = new Set(Object.values(manifest.units).flatMap((u) => ("executor" in u.implementation ? [u.implementation.executor] : [])));
  if (executors.size > 1) throw new LinkError("MissingLibrary", [`forge-native units need ${[...executors].join(" and ")}; one child can load one runtime`]);
  const e = [...executors][0];
  return e ? e.slice(e.lastIndexOf("@") + 1) : "";
};

/** Which blobs a policy's child needs. Throws if a library or app bundle is not in the kit. */
export function childSource(manifest: ClosureManifest, policy: Policy, kit: LinkerKit): ChildSource {
  const units = jsUnits(manifest, policy.units);
  const libraries: Record<string, string> = {};
  const problems: string[] = [];
  const need = (name: string, version: string) => {
    if (libraries[name] && libraries[name] !== version) problems.push(`closure needs ${name}@${libraries[name]} and ${name}@${version}`);
    libraries[name] = version;
  };
  const runtimeVersion = executorVersion(manifest) || units.map((u) => u.libraries[RUNTIME_LIBRARY]).find(Boolean) || "";
  if (!runtimeVersion) problems.push("cannot tell which @forgegraph/runtime executes this manifest");
  need(RUNTIME_LIBRARY, runtimeVersion);
  for (const u of units) for (const [n, v] of Object.entries(u.libraries)) need(n, v);
  // The runtime library is built against Effect; a child always carries the one it was built with.
  if (!libraries[EFFECT_LIBRARY]) {
    const effect = Object.keys(kit.libraries).find((k) => k.startsWith(`${EFFECT_LIBRARY}@`));
    if (effect) libraries[EFFECT_LIBRARY] = effect.slice(EFFECT_LIBRARY.length + 1);
  }
  const blobs: Record<string, string> = {};
  for (const [n, v] of Object.entries(libraries)) {
    const blob = kit.libraries[`${n}@${v}`];
    if (!blob) problems.push(`library ${n}@${v} is not provided by this linker`);
    else blobs[n] = blob;
  }
  const app = kit.apps[manifest.buildHash];
  if (!app) problems.push(`no app bundle for buildHash ${manifest.buildHash}`);
  else blobs["app.json"] = app;
  if (problems.length) throw new LinkError("MissingLibrary", problems);
  const out = units.map((u) => ({ hash: u.hash, symbol: u.unit.symbol, abi: u.abi, moduleName: `u-${u.module.slice("sha256:".length)}.js` }));
  for (const u of units) blobs[`u-${u.module.slice("sha256:".length)}.js`] = u.module;
  return { blobs, libraries, units: out };
}

/** The generated main module. Linker code, not unit code: it sees the capability stubs, never the host env. */
export function childMain(source: ChildSource, policy: Policy, vars: string[]): string {
  const imports = source.units.map((u, i) => `import u${i} from ${JSON.stringify(`./${u.moduleName}`)};`).join("\n");
  const fns = source.units.flatMap((u, i) => (u.abi === "forgegraph-function/1" ? [`[${JSON.stringify(u.symbol)}, u${i}]`] : []));
  const exts = source.units.flatMap((u, i) => (u.abi === "forgegraph-external-binding/1" ? [`[${JSON.stringify(u.symbol)}, u${i}]`] : []));
  return `// Generated by @forgegraph/linker-dynamic for ${policy.label}
import { WorkerEntrypoint } from "cloudflare:workers";
import { createWorker } from "@forgegraph/runtime";
import app from "./app.json";
${imports}

const POLICY = ${JSON.stringify({ label: policy.label, privileged: policy.privileged, objects: policy.objects, queues: policy.queues, workflows: policy.workflows })};
const VARS = ${JSON.stringify(vars)};
const functions = [];
for (const [symbol, impl] of [${fns.join(", ")}]) {
  if (!impl || impl.id !== symbol || typeof impl.body !== "function") throw new Error("linker: module for " + symbol + " does not export its FunctionImpl");
  functions.push(impl);
}
const externals = {};
for (const [symbol, impl] of [${exts.join(", ")}]) {
  if (typeof impl !== "function") throw new Error("linker: module for " + symbol + " does not export an ExternalBinding");
  externals[symbol] = impl;
}
// FORG-29's hand-off option: no child sweeps the outbox in-process. A narrowed child's model has
// only its closure's subscribers, and the dispatcher marks a row done after the subscribers it
// knows, so an in-process sweep would drop other closures' deliveries. The host hands each
// post-commit nudge to the dispatch child's dispatch() instead (fetch gets no ctx either, so this
// holds twice over).
const worker = createWorker(app, { functions, externals, postCommit: async () => undefined });

// D1Like over the host's D1 gate: every statement crosses to the host, which checks its tables.
function d1(gate) {
  const stmt = (sql, params) => ({
    bind: (...values) => stmt(sql, values),
    first: () => gate.first(sql, params),
    all: () => gate.all(sql, params),
    run: () => gate.run(sql, params),
    __forge: { sql, params },
  });
  return { prepare: (sql) => stmt(sql, []), batch: (statements) => gate.batch(statements.map((s) => s.__forge)) };
}
function r2(gate) {
  return {
    head: (key) => gate.head(key),
    get: (key) => gate.get(key),
    put: async (key, value, options) => gate.put(key, value instanceof ReadableStream ? await new Response(value).arrayBuffer() : value, options),
    delete: (key) => gate.delete(key),
  };
}
function workflow(gate) {
  return {
    create: (opts) => gate.create(opts),
    get: async (id) => ({ sendEvent: (e) => gate.sendEvent(id, e) }),
  };
}
// The WorkerEnv the runtime host reads, built from the stubs this child was given and nothing else.
function hostEnv(env) {
  const out = {};
  for (const v of VARS) if (typeof env[v] === "string") out[v] = env[v];
  if (env.DB) out.DB = d1(env.DB);
  for (const b of POLICY.objects) if (env[b]) out[b] = r2(env[b]);
  for (const b of POLICY.queues) if (env[b]) out[b] = { send: (body, options) => env[b].send(body, options) };
  for (const b of POLICY.workflows) if (env[b]) out[b] = workflow(env[b]);
  return out;
}

export default {
  // No ctx: post-commit dispatch and first-sight schedule tracking are the host's job (dispatch child).
  fetch: (request, env) => worker.fetch(request, hostEnv(env)),
};

export class Forge extends WorkerEntrypoint {
  advance(tenant, id) { return worker.advance(hostEnv(this.env), tenant, id); }
  dispatch(tenant, o) { return worker.dispatch(hostEnv(this.env), tenant, o); }
  async scheduled(event) {
    const pending = [];
    await worker.scheduled(event, hostEnv(this.env), { waitUntil: (p) => pending.push(p) });
    await Promise.all(pending);
  }
  async queue(queue, bodies) {
    const outcomes = bodies.map(() => "retry");
    const messages = bodies.map((body, i) => ({ body, ack: () => { outcomes[i] = "ack"; }, retry: () => { outcomes[i] = "retry"; } }));
    await worker.queue({ queue, messages }, hostEnv(this.env));
    return outcomes;
  }
}
`;
}
