//! `forge` — check, fmt, inspect. The compiler core is filesystem-free; this
//! binary is the host that loads packages and their path dependencies.

use anyhow::{anyhow, bail, Context, Result};
use clap::{Parser, Subcommand};
use forge_semantic::{compile, load_package, Compilation, DomainIR, Package};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

#[derive(Parser)]
#[command(name = "forge", version, about = "Forge compiler")]
struct Cli {
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Parse, resolve and check a package and its dependencies.
    Check {
        #[arg(default_value = ".")]
        path: PathBuf,
    },
    /// Format every `.forge` file in a package.
    Fmt {
        #[arg(default_value = ".")]
        path: PathBuf,
        /// Exit 1 if any file would change; write nothing.
        #[arg(long)]
        check: bool,
    },
    /// Print the package's DomainIR as JSON.
    Inspect {
        #[arg(default_value = ".")]
        path: PathBuf,
    },
    /// Compile and write generated artifacts (app bundle, D1 migration, TS client).
    Build {
        #[arg(default_value = ".")]
        path: PathBuf,
        /// Output directory (default: `<package>/generated`).
        #[arg(long)]
        out: Option<PathBuf>,
    },
    /// Write `forge.lock`, pinning dependency contracts and the compiler version.
    Lock {
        #[arg(default_value = ".")]
        path: PathBuf,
    },
    /// Semantic diff between two built bundles (API, interfaces, event, storage, lifecycle, workflow,
    /// classification, governance, dependencies, policy streams). Exit 1 on breaking findings.
    Compat {
        old: PathBuf,
        new: PathBuf,
        /// Render Markdown for an audience instead of JSON: pr | changelog | security.
        #[arg(long)]
        report: Option<String>,
    },
    /// Import a vendor OpenAPI 3.x document (JSON) as a Forge package: pinned refs only, no fetching.
    ImportOpenapi {
        spec: PathBuf,
        /// Forge package name, e.g. `@vendor/billing`.
        #[arg(long)]
        package: String,
        /// Output directory for the generated package.
        #[arg(long)]
        out: PathBuf,
        /// Pin a remote `$ref` URL to a local file: `URL=FILE` or `URL=FILE@SHA256`.
        #[arg(long = "pin")]
        pins: Vec<String>,
        /// Hosts that servers/callbacks may name (repeatable). Empty allows any public host.
        #[arg(long = "allow-host")]
        allow_hosts: Vec<String>,
    },
    /// Governance-aware migration plan between two built bundles (phased DAG; blocked steps named).
    Migrate { old: PathBuf, new: PathBuf },
    /// Language server over stdio (diagnostics, formatting).
    Lsp,
    /// Explain the effective purpose surface of a resource: every granted and denied atom with its origin.
    Explain {
        #[arg(default_value = ".")]
        path: PathBuf,
        /// Resource name (e.g. `Contact`); omit to list every surface.
        #[arg(long)]
        resource: Option<String>,
        #[arg(long)]
        json: bool,
    },
}

mod lsp;

/// `forge.lock` content. Dependencies are pinned by name, version and the
/// content hash of their compiled contract, so a changed upstream contract is
/// detected even when its version string is not bumped.
fn render_lock(deps: &[(String, DomainIR)]) -> String {
    let mut s = String::from("# Generated by `forge lock`; do not edit.\nlock = 1\n");
    s.push_str(&format!("compiler = \"{}\"\n", env!("CARGO_PKG_VERSION")));
    for (name, d) in deps {
        s.push_str(&format!("\n[[dependency]]\nname = \"{name}\"\nversion = \"{}\"\nhash = \"sha256:{}\"\n", d.package.version, d.content_hash()));
    }
    s
}

/// Compare an existing lock with the loaded dependency set. Missing lock: fine (warn).
fn verify_lock(root: &Path, deps: &[(String, DomainIR)]) -> Result<()> {
    let path = root.join("forge.lock");
    let Ok(existing) = std::fs::read_to_string(&path) else {
        if !deps.is_empty() {
            eprintln!("warning[W-LOCK-001]: forge.lock is missing; run `forge lock` to pin dependencies");
        }
        return Ok(());
    };
    let expected = render_lock(deps);
    if existing != expected {
        eprintln!("error[E-LOCK-001]: forge.lock is stale: a dependency contract or the compiler version changed; run `forge lock` after reviewing the change");
        std::process::exit(1);
    }
    Ok(())
}

struct Loaded {
    package: Package,
    compilation: Compilation,
    /// Dependencies in topological order (name, ir).
    deps: Vec<(String, DomainIR)>,
}

/// Load and compile a package after its path dependencies, depth-first.
fn load_tree(root: &Path, seen: &mut BTreeMap<PathBuf, DomainIR>, stack: &mut Vec<PathBuf>) -> Result<Loaded> {
    let canon = root.canonicalize().with_context(|| format!("{}", root.display()))?;
    if stack.contains(&canon) {
        bail!("dependency cycle through {}", canon.display());
    }
    stack.push(canon.clone());
    let package = load_package(&canon).map_err(|e| anyhow!("{e}"))?;
    let mut deps = Vec::new();
    let mut dep_irs: Vec<DomainIR> = Vec::new();
    for (alias, path) in &package.dependency_paths {
        let dep_canon = path.canonicalize().with_context(|| format!("dependency `{alias}` at {}", path.display()))?;
        let ir = match seen.get(&dep_canon) {
            Some(ir) => ir.clone(),
            None => {
                let loaded = load_tree(&dep_canon, seen, stack)?;
                let rendered = loaded.compilation.render();
                let Some(ir) = loaded.compilation.ir else {
                    eprint!("{rendered}");
                    bail!("dependency `{}` has errors", loaded.package.name);
                };
                seen.insert(dep_canon, ir.clone());
                ir
            }
        };
        deps.push((ir.package.name.clone(), ir.clone()));
        dep_irs.push(ir);
    }
    let compilation = compile(&package, &dep_irs.iter().collect::<Vec<_>>());
    stack.pop();
    Ok(Loaded { package, compilation, deps })
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.cmd {
        Cmd::Check { path } => {
            let loaded = load_tree(&path, &mut BTreeMap::new(), &mut Vec::new())?;
            verify_lock(&path, &loaded.deps)?;
            verify_extensions(&loaded.package)?;
            eprint!("{}", loaded.compilation.render());
            let errors = loaded.compilation.diagnostics.iter().filter(|d| d.is_error()).count();
            let warnings = loaded.compilation.diagnostics.len() - errors;
            if errors > 0 {
                eprintln!("{}: {errors} error(s), {warnings} warning(s)", loaded.package.name);
                std::process::exit(1);
            }
            println!("{}: ok ({} file(s), {} dependency(ies), {warnings} warning(s))", loaded.package.name, loaded.package.files.len(), loaded.deps.len());
        }
        Cmd::Fmt { path, check } => {
            let package = load_package(&path).map_err(|e| anyhow!("{e}"))?;
            let mut changed = Vec::new();
            for f in &package.files {
                let parsed = forge_syntax::parse(&f.text);
                if !parsed.errors().is_empty() {
                    eprintln!("{}: skipped (syntax errors)", f.path);
                    continue;
                }
                let formatted = forge_syntax::format(&parsed);
                if formatted != f.text {
                    changed.push(f.path.clone());
                    if !check {
                        std::fs::write(path.join(&f.path), formatted)?;
                    }
                }
            }
            for c in &changed {
                println!("{c}");
            }
            if check && !changed.is_empty() {
                std::process::exit(1);
            }
        }
        Cmd::Build { path, out } => {
            let loaded = load_tree(&path, &mut BTreeMap::new(), &mut Vec::new())?;
            verify_lock(&path, &loaded.deps)?;
            eprint!("{}", loaded.compilation.render());
            let Some(ir) = loaded.compilation.ir else { std::process::exit(1) };
            let plans = match forge_planner::plan(&ir) {
                Ok(p) => p,
                Err(e) => {
                    eprintln!("{e}");
                    std::process::exit(1);
                }
            };
            let out_dir = out.unwrap_or_else(|| path.join("generated"));
            std::fs::create_dir_all(out_dir.join("d1"))?;
            let openapi = forge_codegen::openapi(&plans.contracts, &plans.observability);
            let bundle = serde_json::json!({
                "version": "app-bundle/1",
                "buildHash": build_hash(&ir, &loaded.deps),
                "digests": ir.digests(),
                "ir": ir,
                "contracts": plans.contracts,
                "sql": plans.sql,
                "dynamo": plans.dynamo,
                "ui": plans.ui,
                "messaging": plans.messaging,
                "workflows": plans.workflows,
                "schedules": plans.schedules,
                "realtime": plans.realtime,
                "observability": plans.observability,
                "dataSemantics": forge_semantic::ir::DataSemantics::of(&ir, &forge_semantic::ir::Taxonomy::core()),
                "lineage": forge_semantic::ir::Lineage::of(&ir),
                "capabilities": forge_semantic::ir::EffectiveCapabilities::of(&ir),
                // Served at /forge/openapi.json by every host: the runtime is a consumer of the projection, not its author.
                "openapi": openapi,
            });
            std::fs::write(out_dir.join("app.json"), serde_json::to_string_pretty(&bundle)?)?;
            std::fs::write(out_dir.join("d1/0001_init.sql"), forge_planner::sql::render_sqlite(&plans.sql))?;
            std::fs::create_dir_all(out_dir.join("postgres"))?;
            std::fs::write(out_dir.join("postgres/0001_init.sql"), forge_planner::sql::render_postgres(&plans.sql))?;
            std::fs::write(out_dir.join("client.ts"), forge_codegen::client_ts(&plans.contracts))?;
            std::fs::write(out_dir.join("openapi.json"), serde_json::to_string_pretty(&openapi)?)?;
            std::fs::write(out_dir.join("api.smithy"), forge_codegen::smithy(&plans.contracts))?;
            std::fs::write(out_dir.join("README.md"), "Generated by `forge build`; disposable, do not edit.\n")?;
            println!("{}: wrote {}", loaded.package.name, out_dir.display());
        }
        Cmd::Lock { path } => {
            let loaded = load_tree(&path, &mut BTreeMap::new(), &mut Vec::new())?;
            std::fs::write(path.join("forge.lock"), render_lock(&loaded.deps))?;
            println!("{}: wrote forge.lock ({} dependency(ies))", loaded.package.name, loaded.deps.len());
        }
        Cmd::Explain { path, resource, json } => {
            let loaded = load_tree(&path, &mut BTreeMap::new(), &mut Vec::new())?;
            eprint!("{}", loaded.compilation.render());
            let Some(ir) = loaded.compilation.ir else { std::process::exit(1) };
            let caps = forge_semantic::ir::EffectiveCapabilities::of(&ir);
            let surfaces: Vec<&forge_semantic::ir::Surface> = caps.surfaces.iter().filter(|s| resource.as_ref().is_none_or(|r| s.resource.ends_with(&format!("/{r}")))).collect();
            if json {
                println!("{}", serde_json::to_string_pretty(&surfaces)?);
            } else {
                for s in surfaces {
                    println!("{} for {} (digest {}) via {}", s.resource, s.purpose, &s.digest[..12], s.capabilities.join(" + "));
                    for a in &s.allow_atoms {
                        println!("  allow {:<8} {:<24} from {}", a.verb, a.name, a.origin.join(" > "));
                    }
                    for d in &s.deny {
                        println!("  deny  {:<8} {:<24} from {}", d.verb, d.name, d.origin.join(" > "));
                    }
                }
            }
        }
        Cmd::ImportOpenapi { spec, package, out, pins, allow_hosts } => {
            let text = std::fs::read_to_string(&spec)?;
            let mut opts = forge_codegen::openapi_import::ImportOptions { package, allow_hosts, pins: Vec::new() };
            for p in pins {
                let (url, rest) = p.split_once('=').ok_or_else(|| anyhow::anyhow!("--pin expects URL=FILE[@SHA256], got {p}"))?;
                let (file, sha) = rest.rsplit_once('@').map(|(f, s)| (f.to_string(), Some(s.to_string()))).unwrap_or((rest.to_string(), None));
                opts.pins.push(forge_codegen::openapi_import::Pin { url: url.to_string(), file: PathBuf::from(file), sha256: sha });
            }
            match forge_codegen::openapi_import::import_openapi(&text, &opts) {
                Ok(result) => {
                    for (rel, content) in &result.files {
                        let target = out.join(rel);
                        if let Some(parent) = target.parent() {
                            std::fs::create_dir_all(parent)?;
                        }
                        std::fs::write(target, content)?;
                    }
                    let r = &result.report;
                    eprintln!("{}: imported {} operations ({} skipped), {} unsupported features, {} foreign identifiers, {} callbacks/webhooks -> {}", r.package, r.operations.len(), r.skipped_operations.len(), r.unsupported.len(), r.foreign_identifiers.len(), r.callbacks.len(), out.display());
                    if !r.unsupported.is_empty() || !r.foreign_identifiers.is_empty() {
                        eprintln!("review {} and {}", out.join("import-report.json").display(), out.join("FOREIGN_IDS.md").display());
                    }
                }
                Err(e) => {
                    eprintln!("import refused: {e}");
                    std::process::exit(1);
                }
            }
        }
        Cmd::Migrate { old, new } => {
            let o: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&old)?)?;
            let n: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&new)?)?;
            for (label, v) in [("old", &o), ("new", &n)] {
                if let Err(e) = DomainIR::load(&v["ir"]) {
                    bail!("{label} bundle: {e}");
                }
            }
            let report = forge_semantic::diff::compare(&o, &n);
            let plan = forge_planner::migrations::plan_migration(&report, &o, &n);
            println!("{}", serde_json::to_string_pretty(&plan)?);
            if plan.blocked {
                std::process::exit(2);
            }
        }
        Cmd::Lsp => lsp::run()?,
        Cmd::Compat { old, new, report: audience } => {
            let o: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&old)?)?;
            let n: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&new)?)?;
            // Fail closed on artifacts this build cannot interpret (plan §4.2).
            for (label, v) in [("old", &o), ("new", &n)] {
                if let Err(e) = DomainIR::load(&v["ir"]) {
                    bail!("{label} bundle: {e}");
                }
            }
            let report = forge_semantic::diff::compare(&o, &n);
            match audience {
                Some(a) => print!("{}", forge_semantic::diff::render(&report, &a)),
                None => println!("{}", serde_json::to_string_pretty(&report)?),
            }
            if report.verdict == "breaking" {
                std::process::exit(1);
            }
        }
        Cmd::Inspect { path } => {
            let loaded = load_tree(&path, &mut BTreeMap::new(), &mut Vec::new())?;
            eprint!("{}", loaded.compilation.render());
            let Some(ir) = loaded.compilation.ir else { std::process::exit(1) };
            let out = serde_json::json!({
                "buildHash": build_hash(&ir, &loaded.deps),
                "digests": ir.digests(),
                "dependencies": loaded.deps.iter().map(|(name, d)| serde_json::json!({ "package": name, "hash": d.content_hash() })).collect::<Vec<_>>(),
                "ir": ir,
            });
            println!("{}", serde_json::to_string_pretty(&out)?);
        }
    }
    Ok(())
}

/// FORGE-030: pinned extension manifests are read as bytes, digest-checked and shape-validated.
/// They declare capabilities; nothing in them is ever executed by the compiler.
fn verify_extensions(pkg: &forge_semantic::Package) -> Result<()> {
    const FORBIDDEN: &[&str] = &["main", "exports", "scripts", "bin", "module", "require", "install", "postinstall", "code", "script"];
    for e in &pkg.extensions {
        let bytes = std::fs::read(&e.manifest).with_context(|| format!("extension `{}`: {}", e.name, e.manifest.display()))?;
        let digest = { use sha2::Digest; hex::encode(sha2::Sha256::digest(&bytes)) };
        if digest != e.sha256.trim_start_matches("sha256:") {
            bail!("error[E-EXT-001]: extension `{}` manifest digest {digest} does not match the pinned {}; review the change and re-pin", e.name, e.sha256);
        }
        let v: serde_json::Value = serde_json::from_slice(&bytes).with_context(|| format!("error[E-EXT-002]: extension `{}` manifest is not JSON", e.name))?;
        let Some(obj) = v.as_object() else { bail!("error[E-EXT-002]: extension `{}` manifest must be an object", e.name) };
        if let Some(k) = obj.keys().find(|k| FORBIDDEN.contains(&k.as_str())) {
            bail!("error[E-EXT-002]: extension `{}` manifest carries an executable entry `{k}`; manifests declare capabilities and never run", e.name);
        }
        if obj.get("version").and_then(|x| x.as_str()) != Some("capability-manifest/1") {
            bail!("error[E-EXT-002]: extension `{}` manifest version must be capability-manifest/1", e.name);
        }
        for k in ["id", "kind", "adapterVersion", "engine", "runtime", "capabilities"] {
            if obj.get(k).is_none() {
                bail!("error[E-EXT-002]: extension `{}` manifest is missing `{k}`", e.name);
            }
        }
        for c in obj["capabilities"].as_array().cloned().unwrap_or_default() {
            let support = c["support"].as_str().unwrap_or("");
            if support != "unsupported" && c["evidence"].as_array().is_none_or(|a| a.is_empty()) {
                bail!("error[E-EXT-002]: extension `{}` claims `{}` as {support} without evidence references (no self-certification)", e.name, c["id"]);
            }
        }
    }
    Ok(())
}

/// Build identity per specs/language/identity.md: package IR content, dependency
/// hashes, and the compiler version. No timestamps or machine paths.
fn build_hash(ir: &DomainIR, deps: &[(String, DomainIR)]) -> String {
    use std::fmt::Write;
    let mut material = String::new();
    let _ = write!(material, "compiler={};ir={};", env!("CARGO_PKG_VERSION"), ir.content_hash());
    for (name, d) in deps {
        let _ = write!(material, "dep:{name}={};", d.content_hash());
    }
    forge_semantic::ir::hash_hex(&material)
}
